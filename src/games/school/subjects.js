export const poolOf = (subject) => QUESTIONS[subject] || [];
export const hasPool = (subject) => (QUESTIONS[subject] || []).length > 0;

/** 出題する n 問を、その科目のプールから決まった順で選ぶ（塾・赤本はここを覗く） */
export function drawQuestions(subject, n, seed = 0) {
  const pool = poolOf(subject);
  if (!pool.length) return [];
  const idx = pool.map((_, i) => i);
  // シードつきシャッフル
  let t = (seed * 2654435761) >>> 0;
  const rnd = () => { t = (t * 1664525 + 1013904223) >>> 0; return t / 4294967296; };
  for (let i = idx.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1));[idx[i], idx[j]] = [idx[j], idx[i]]; }
  return idx.slice(0, Math.min(n, idx.length)).map(i => pool[i]);
}
